const pad = (n) => String(n).padStart(2, "0");
const ymd = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

// Fresh seed documents in the stored shape (see mockAnnouncements.js). All are
// published.
export function makeSeedAnnouncements(now = new Date()) {
  const stamp = now.toISOString();
  return SEEDS.map(({ daysAgo, pdf, ...s }) => {
    const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() - daysAgo);
    return {
      ...s,
      date: ymd(d),
      sample: true,
      status: "published",
      createdAt: stamp,
      updatedAt: stamp,
      updatedBy: null,
      pdf: pdf ? { kind: "static", url: pdf.url, name: pdf.name, size: pdf.size } : null,
    };
  });
}
